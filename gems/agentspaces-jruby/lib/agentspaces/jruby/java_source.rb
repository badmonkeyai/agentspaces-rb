require "digest"

module AgentSpaces
  module JRuby
    # Writes the Java source the JavaEngine compiles: a record per Entry the
    # classpath does not already hold, and one annotated interface per agent
    # shape (SRAD 3.6, RB-J-03, RB-J-04). The source is built only from
    # validated identifiers and escaped string literals, so no configuration
    # value reaches a class name, a method name, or code.
    module JavaSource
      IDENTIFIER = /\A[A-Za-z_$][A-Za-z0-9_$]*\z/
      RESERVED = %w[abstract assert boolean break byte case catch char class const continue default do double else
                    enum extends final finally float for goto if implements import instanceof int interface long
                    native new package private protected public return short static strictfp super switch
                    synchronized this throw throws transient try void volatile true false null record var yield
                    sealed permits].freeze
      PACKAGE = "ai.badmonkey.agentspaces.jruby.generated"
      ANNOTATION = "ai.badmonkey.agentspaces.agent.annotation"
      PROPOSAL = "ai.badmonkey.agentspaces.capabilities.vote.VoteCapability.Proposal"
      DECISION = "ai.badmonkey.agentspaces.capabilities.vote.VoteCapability.Decision"
      JOINED = "ai.badmonkey.agentspaces.agent.join.Joined"
      CAMEL = { result_space: "resultSpace", result_lease: "resultLease", poll_timeout: "pollTimeout",
                key_tag: "keyTag", max_open: "maxOpen", at_least: "atLeast" }.freeze

      module_function

      def identifier!(name, what)
        text = name.to_s
        unless IDENTIFIER.match?(text) && !RESERVED.include?(text)
          raise EngineUnsupported, "#{what} #{text.inspect} is not a Java identifier the Java binder can carry"
        end

        text
      end

      # "shop.Order#v1" to "shop.Order"; a binary name with "$" is a nested
      # class, which only an existing class can be.
      def class_name(schema)
        name = schema.to_s.sub(/#v\d+\z/, "")
        parts = name.split(".")
        raise EngineUnsupported, "schema #{schema.inspect} names no Java class" if parts.size < 2

        parts.each { |part| part.split("$").each { |p| identifier!(p, "schema segment") } }
        name
      end

      # A Java string literal. The quote and the backslash take their escapes,
      # control characters octal ones, and anything beyond ASCII a \uXXXX
      # escape. Java translates \uXXXX before it lexes, so " would end
      # the literal; that is why the quote never travels that way.
      def literal(value)
        escaped = value.to_s.each_codepoint.map do |cp|
          if cp == 0x22 then '\\"'
          elsif cp == 0x5C then "\\\\"
          elsif cp < 0x20 || cp == 0x7F then format('\\%03o', cp)
          elsif cp < 0x7F then cp.chr
          elsif cp > 0xFFFF
            [cp].pack("U").encode("UTF-16BE").unpack("n*").map { |u| format('\\u%04x', u) }.join
          else
            format('\\u%04x', cp)
          end
        end.join
        "\"#{escaped}\""
      end

      def strings(values) = "{#{Array(values).map { |v| literal(v) }.join(', ')}}"

      # The Java type of an Entry field.
      def field_type(type, names, boxed: false)
        if type.is_a?(Array)
          "java.util.List<#{field_type(type.first, names, boxed: true)}>"
        elsif type == String || type == :instant then "String"
        elsif type == Integer then boxed ? "Long" : "long"
        elsif type == Float then boxed ? "Double" : "double"
        elsif type == :boolean then boxed ? "Boolean" : "boolean"
        elsif type == :bytes then "byte[]"
        elsif type == Hash then "java.util.Map<String, Object>"
        elsif Entry.entry_class?(type) then names.fetch(type)
        else "Object"
        end
      end

      # The source of a record for one Entry class.
      def record(entry, names)
        name = names.fetch(entry)
        package, _, simple = name.rpartition(".")
        components = entry.fields.map do |f|
          "#{field_type(f.type, names)} #{identifier!(f.wire, "field #{f.name} wire name")}"
        end
        "package #{package};\n\n/** Generated by agentspaces-jruby for #{entry.schema}. */\n" \
          "public record #{simple}(#{components.join(', ')}) {}\n"
      end

      # Turns where: and tags: options into the Java binder's portable clauses.
      def where_clauses(entry, where)
        case where
        when nil then []
        when String then [where]
        when Array then where.map(&:to_s)
        when Hash
          where.flat_map do |key, spec|
            wire = Entry.entry_class?(entry) ? entry.field(key)&.wire || key.to_s : key.to_s
            clause(wire, spec)
          end
        else raise EngineUnsupported, "where: #{where.inspect} has no portable form"
        end
      end

      def clause(wire, spec)
        case spec
        when String, Numeric, true, false then ["#{wire}=#{spec}"]
        when Array then ["#{wire} in #{spec.join(',')}"]
        when Range
          parts = []
          parts << "#{wire}>=#{spec.begin}" unless spec.begin.nil?
          parts << "#{wire}#{spec.exclude_end? ? '<' : '<='}#{spec.end}" unless spec.end.nil?
          parts
        else
          raise EngineUnsupported, "#{wire}: #{spec.inspect} is a local matcher; the Java binder takes values, " \
                                   "ranges, arrays, and clause strings (\"#{wire}>=3\")"
        end
      end

      def tag_clauses(tags)
        (tags || {}).map do |key, spec|
          case spec
          when true then key.to_s
          when String, Numeric then "#{key}=#{spec}"
          else raise EngineUnsupported, "tags: #{key} => #{spec.inspect} has no portable form; use a value or true"
          end
        end
      end

      def attributes(pairs)
        pairs.reject { |_, v| v.nil? }.map { |k, v| "#{k} = #{v}" }.join(", ")
      end

      def common(options, names, entry)
        produces = Array(options[:produces_classes]).map { |c| "#{names.fetch(c)}.class" }
        {
          "space" => options[:space] && literal(options[:space]),
          "group" => options[:group] && literal(options[:group]),
          "lease" => options[:lease] && literal(options[:lease]),
          "pollTimeout" => options[:poll_timeout] && literal(options[:poll_timeout]),
          "resultSpace" => options[:result_space] && literal(options[:result_space]),
          "resultLease" => options[:result_lease] && literal(options[:result_lease]),
          "description" => options[:description] && literal(options[:description]),
          "tags" => options.key?(:tags) ? strings(tag_clauses(options[:tags])) : nil,
          "where" => options.key?(:where) ? strings(where_clauses(entry, options[:where])) : nil,
          "produces" => produces.empty? ? nil : "{#{produces.join(', ')}}"
        }
      end

      # The planner contract's attributes, each left to the annotation's default when unset.
      def contract(options)
        {
          "pre" => options[:pre] && strings(options[:pre]),
          "post" => options[:post] && strings(options[:post]),
          "cost" => options[:cost].to_s.empty? ? nil : literal(options[:cost])
        }
      end

      # One annotated abstract method per clause; returns [annotation line, signature].
      def method_for(clause, names)
        options = clause.options.merge(produces_classes: clause.produces.select { |p| Entry.entry_class?(p) })
        cue = clause.cue
        produced = options[:produces_classes]
        result = produced.size == 1 ? names.fetch(produced.first) : "Object"
        method = identifier!(clause.method_name, "method name")
        base = common(options, names, cue)
        case clause.verb
        when :take
          ["@#{ANNOTATION}.SpaceTake(#{attributes(base.merge(contract(options)))})",
           "#{result} #{method}(#{names.fetch(cue)} cue)"]
        when :ordered_take
          ["@#{ANNOTATION}.OrderedTake(#{attributes(base.merge(contract(options)))})",
           "#{result} #{method}(#{names.fetch(cue)} cue)"]
        when :notify
          kinds = Array(options[:on]).map { |k| "ai.badmonkey.agentspaces.api.space.SpaceEvent.Kind.#{identifier!(k, 'event kind')}" }
          notify = base.merge("on" => "{#{kinds.join(', ')}}")
          ["@#{ANNOTATION}.SpaceNotify(#{attributes(notify)})", "#{result} #{method}(#{names.fetch(cue)} cue)"]
        when :bid
          ["@#{ANNOTATION}.BidFunction(#{attributes(base.slice('space', 'group'))})",
           "double #{method}(#{names.fetch(cue)} cue)"]
        when :ballot
          attrs = base.slice("space", "group", "lease").merge("prefix" => literal(options[:prefix].to_s))
          ["@#{ANNOTATION}.Ballot(#{attributes(attrs)})", "String #{method}(#{PROPOSAL} proposal)"]
        when :on_decision
          attrs = base.slice("space", "group", "resultSpace", "resultLease").merge("prefix" => literal(options[:prefix].to_s))
          ["@#{ANNOTATION}.OnDecision(#{attributes(attrs)})", "#{result} #{method}(#{DECISION} decision)"]
        when :propose
          attrs = base.slice("space", "group", "lease", "tags", "where", "description").merge(
            "vote" => literal(options[:vote]), "prefix" => literal(options[:prefix].to_s),
            "key" => strings(Array(options[:key]).map { |k| cue.field(k)&.wire || k.to_s }),
            "keyTag" => options[:key_tag] && literal(options[:key_tag]),
            "options" => strings(options[:options]), "quorum" => Integer(options[:quorum]).to_s
          )
          ["@#{ANNOTATION}.Propose(#{attributes(attrs)})", "Object #{method}(#{names.fetch(cue)} cue)"]
        when :join
          parts = options[:parts].map do |part|
            part_attrs = {
              "value" => "#{names.fetch(part.type)}.class",
              "space" => part.space && literal(part.space),
              "key" => part.key && literal(part.type.field(part.key)&.wire || part.key.to_s),
              "keyTag" => part.key_tag && literal(part.key_tag),
              "optional" => part.optional ? "true" : nil,
              "atLeast" => part.at_least.to_i == 1 ? nil : Integer(part.at_least).to_s,
              "where" => part.where || !part.filters.empty? ? strings(where_clauses(part.type, part.where) + part.filters) : nil,
              "tags" => part.tags && strings(tag_clauses(part.tags))
            }
            "@#{ANNOTATION}.Part(#{attributes(part_attrs)})"
          end
          mode = identifier!(options[:mode].to_s.upcase, "join mode")
          key_field = options[:parts].first.type.field(options[:key])&.wire || options[:key].to_s
          attrs = base.slice("space", "group", "resultSpace", "resultLease", "description", "produces").merge(
            "key" => literal(key_field), "parts" => "{#{parts.join(', ')}}",
            "mode" => "#{ANNOTATION}.SpaceJoin.Mode.#{mode}", "within" => literal(options[:within]),
            "maxOpen" => Integer(options[:max_open]).to_s
          )
          ["@#{ANNOTATION}.SpaceJoin(#{attributes(attrs)})", "#{result} #{method}(#{JOINED} joined)"]
        when :reduce
          accumulator = produced.first or raise EngineUnsupported, "reduce needs produces: the accumulator Entry"
          attrs = base.slice("space", "group", "description", "produces", "tags", "where", "lease", "pollTimeout").merge(
            "key" => options[:key] && literal(cue.field(options[:key])&.wire || options[:key].to_s),
            "keyTag" => options[:key_tag] && literal(options[:key_tag]),
            "maxOpen" => Integer(options[:max_open]).to_s,
            "mode" => "#{ANNOTATION}.SpaceReduce.Mode.#{identifier!(options[:mode].to_s.upcase, 'reduce mode')}"
          )
          acc = names.fetch(accumulator)
          ["@#{ANNOTATION}.SpaceReduce(#{attributes(attrs)})", "#{acc} #{method}(#{acc} accumulator, #{names.fetch(cue)} cue)"]
        else
          raise EngineUnsupported, "#{clause.verb} does not bind on the JRuby face yet"
        end
      end

      # The source of the annotated interface for one agent model; returns
      # [fully qualified name, source].
      def interface(model, names)
        methods = model.clauses.map { |c| method_for(c, names) }
        body = methods.map { |annotation, signature| "    #{annotation}\n    #{signature};\n" }.join("\n")
        digest = Digest::SHA256.hexdigest([model.name, model.description, model.goals, body].inspect)[0, 16]
        simple = "Agent_#{digest}"
        spec = attributes("name" => literal(model.name), "description" => literal(model.description),
                          "goals" => strings(model.goals))
        source = "package #{PACKAGE};\n\n/** Generated by agentspaces-jruby for agent #{model.name.gsub(/[^\w-]/, '_')}. */\n" \
                 "@#{ANNOTATION}.AgentSpec(#{spec})\npublic interface #{simple} {\n#{body}}\n"
        ["#{PACKAGE}.#{simple}", source]
      end
    end
  end
